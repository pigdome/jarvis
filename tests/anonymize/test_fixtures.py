"""Smoke tests for the committed synthetic dumps (no docker needed).

The dumps are regenerated by ``tests/fixtures/anonymize/make_fixtures.sh``.
These checks guard the properties the stream rewriters depend on: real
mysqldump/pg_dump framing, extended INSERTs long enough to split, and the
escaping edge cases from the design review.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from conftest import FIXTURE_DIR, MYSQL_DUMP, PG_DUMP  # noqa: E402


def test_fixtures_exist():
    assert FIXTURE_DIR.is_dir()
    assert MYSQL_DUMP.is_file(), f"missing {MYSQL_DUMP} - run make_fixtures.sh"
    assert PG_DUMP.is_file(), f"missing {PG_DUMP} - run make_fixtures.sh"
    assert MYSQL_DUMP.stat().st_size > 100_000
    assert PG_DUMP.stat().st_size > 1_000

    mysql = MYSQL_DUMP.read_bytes()
    pg = PG_DUMP.read_bytes()
    assert b"MariaDB dump" in mysql or b"MySQL dump" in mysql
    assert b"PostgreSQL database dump" in pg


def test_mysql_fixture_covers_review_cases():
    mysql = MYSQL_DUMP.read_bytes()

    # hundreds of rows per INSERT: the fixture must produce several statements
    assert mysql.count(b"INSERT INTO `borrowers`") >= 2
    assert b"'S003000'" in mysql  # 3000 generated rows

    assert "สมชาย ใจดี".encode() in mysql  # Thai UTF-8
    assert b"O\\'Brien" in mysql  # escaped single quote
    assert b"Back\\\\slash" in mysql  # escaped backslash
    assert b"\\n" in mysql and b"\\t" in mysql  # newline / tab in TEXT
    assert b"0000-00-00" in mysql  # zero date needs sql_mode = ''
    assert b"'sess-001','\\0\xff\\''" in mysql  # LONGBLOB 0x00FF27, binary escapes

    # tables with no rules / truncated tables are present for passthrough tests
    assert b"INSERT INTO `issues`" in mysql
    assert b"INSERT INTO `biblio`" in mysql
    assert b"INSERT INTO `sessions`" in mysql
    assert b"INSERT INTO `borrower_attributes`" in mysql
    assert b"CITIZENID" in mysql and b"FACULTY" in mysql


def test_pg_fixture_covers_review_cases():
    pg = PG_DUMP.read_bytes()

    assert pg.count(b"COPY public.eperson ") == 1
    assert pg.count(b"COPY public.metadatavalue ") == 1
    for table in (
        b"metadataschemaregistry",
        b"metadatafieldregistry",
        b"booking_patron",
        b"booking_booking",
        b"booking_actionlog",
        b"django_session",
    ):
        assert pg.count(b"COPY public." + table + b" ") == 1

    assert "สมชาย ใจดี".encode() in pg  # Thai UTF-8
    assert b"O'Brien" in pg  # apostrophe is not escaped in COPY text format
    assert b"\\\\" in pg  # backslash escape
    assert b"\\t" in pg and b"\\n" in pg  # tab / newline escapes inside a field
    assert b"\\N" in pg  # NULL marker
    assert b"firstname" in pg and b"lastname" in pg

    # pg_dump 16.10+ guards the dump; if present the key must be released again.
    if b"\n\\restrict " in pg:
        key = pg.split(b"\n\\restrict ", 1)[1].split()[0]
        assert b"\n\\unrestrict " + key in pg
